const fs=require('fs'),path=require('path'),assert=require('assert/strict');
const {pathToFileURL,fileURLToPath}=require('url');
const {chromium}=require(process.env.BMC_PLAYWRIGHT_MODULE||'playwright');
(async()=>{
 const root=path.resolve(process.env.BMC_HTML_REPORT_QA||'bmca-runtime/verification/compact-report/html-actual');
 const browser=await chromium.launch({executablePath:process.env.BMC_CHROME_PATH||path.join(process.env.ProgramFiles||'C:/Program Files','Google/Chrome/Application/chrome.exe'),headless:true});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[],remote=[];
  page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(/^https?:/.test(r.url()))remote.push(r.url());});
  const start=Date.now();await page.goto(pathToFileURL(path.join(root,'BMC_Report.html')).href);
  assert.equal(await page.locator('details[open]').count(),0);
  const count=await page.locator('.case').count();
  assert.equal(await page.locator('.case-heading .status:visible').count(),count);
  assert.equal(await page.locator('.description').first().isVisible(),false);
  assert.equal(await page.locator('pre,dialog,[data-view]').count(),0);
  assert.ok((await page.locator('body').innerText()).length<30000);
  const collapsedLoadMs=Date.now()-start;
  await page.screenshot({path:path.join(root,'collapsed.png'),fullPage:false});
  const heading=page.locator('.case-heading').first();
  await heading.focus();await page.keyboard.press('Enter');
  assert.equal(await page.locator('details[open]').count(),1);
  assert.equal(await page.locator('.description').first().isVisible(),true);
  assert.equal(await page.locator('.test-information').first().isVisible(),true);
  assert.equal(await page.locator('.case').first().locator('summary').count(),1);
  assert.equal(await page.locator('.test-data .method-table').first().isVisible(),true);
  assert.match(await page.locator('.test-information').first().innerText(),/UTC\+08:00/);
  assert.deepEqual(await page.locator('.test-information').first().locator('dt').allTextContents(),['Task Name','Tester','Execution Time','FW Package','Configuration']);
  await heading.click();assert.equal(await page.locator('details[open]').count(),0);
  await heading.click();assert.equal(await page.locator('details[open]').count(),1);
  assert.equal(await page.locator('.method-table').first().isVisible(),true);
  assert.deepEqual(await page.locator('.method-table').first().locator('th').allTextContents(),['Step','Type','Description','Result','Judgement']);
  const rows=await page.locator('.method-table').first().locator('tbody tr').evaluateAll(rows=>rows.map(r=>[...r.cells].map(c=>c.textContent)));
  assert.deepEqual(rows[0].slice(0,2),['1','Command']);
  assert.equal(rows[1][0],'');assert.equal(rows[1][4],'PASS');
  assert.equal(rows[12][1],'Record');assert.equal(rows[12][4],'COMPLETED');
  assert.ok(!rows.flat().some(t=>/C2a|Source: S|RECORDED/.test(t)));
  assert.equal(await page.locator('.method-table td').first().evaluate(el=>getComputedStyle(el).paddingTop),'3px');
  assert.equal(await page.locator('dl.data-fields').first().evaluate(el=>getComputedStyle(el).rowGap),'6px');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  const font=await page.locator('.case-title').first().evaluate(el=>{const s=getComputedStyle(el);return [s.fontSize,s.fontWeight,s.fontFamily];});
  assert.equal(font[0],'22px');assert.equal(font[1],'600');assert.ok(font[2].includes('Bahnschrift'));
  const open=page.locator('a[target=_blank]').first(),href=await open.getAttribute('href');
  assert.ok(fs.readFileSync(fileURLToPath(new URL(href,page.url()))).length>0);
  const [popup]=await Promise.all([page.waitForEvent('popup'),open.click()]);await popup.waitForLoadState();
  assert.ok(popup.url().includes('/logs/'));await popup.close();
  await page.screenshot({path:path.join(root,'expanded.png'),fullPage:false});
  await page.evaluate(()=>{window.printCalls=0;window.print=()=>{window.printCalls++;window.dispatchEvent(new Event('beforeprint'));};});
  await page.locator('#print-report').click();assert.equal(await page.evaluate(()=>window.printCalls),1);
  assert.equal(await page.locator('details[open]').count(),await page.locator('details').count());
  await page.pdf({path:path.join(root,'browser-print.pdf'),format:'A4',printBackground:true});
  await page.evaluate(()=>window.dispatchEvent(new Event('afterprint')));
  assert.equal(await page.locator('details[open]').count(),1);
  assert.deepEqual(errors,[]);assert.deepEqual(remote,[]);
  console.log('PASS: compact typed method table, no overflow, offline attachments, print and restored state; load ms',collapsedLoadMs);
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
